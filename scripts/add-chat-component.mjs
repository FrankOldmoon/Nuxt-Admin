#!/usr/bin/env node
/**
 * Scaffold a chat component.
 *
 *   pnpm module:add-component sms sms.leave-table 请假表格 [--resource leave] [--apps /dashboard/leave]
 *
 * Creates:
 *   1. the Vue component (id → filename convention used by the client map)
 *   2. a contract test for the props schema
 *   3. a registration entry in modules/<module>/server/chatComponents.generated.ts
 *
 * No dependency on any package: keep it runnable with plain node.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const root = resolve(process.cwd())
const args = process.argv.slice(2)
const positional = args.filter(argument => !argument.startsWith('--'))
const flags = new Map()
for (let i = 0; i < args.length; i++) {
  if (!args[i].startsWith('--')) continue
  const key = args[i].slice(2)
  const value = args[i + 1] && !args[i + 1].startsWith('--') ? args[++i] : ''
  flags.set(key, value)
}

const [moduleId, componentId, label] = positional
if (!moduleId || !componentId || !label) {
  console.error('Usage: pnpm module:add-component <module> <component.id> "<label>" [--resource <table>] [--apps <path>]')
  process.exit(1)
}
if (!componentId.startsWith(`${moduleId}.`)) {
  console.error(`Component id must start with "${moduleId}."`)
  process.exit(1)
}

const moduleDir = join(root, 'modules', moduleId)
if (!existsSync(moduleDir)) {
  console.error(`Unknown module: modules/${moduleId}`)
  process.exit(1)
}

const tail = componentId.split('.').pop()
const pascal = tail.split(/[-_]/).filter(Boolean)
  .map(part => part.charAt(0).toUpperCase() + part.slice(1))
  .join('')
const kebab = tail.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`)
const resource = flags.get('resource') || kebab
const appsPath = flags.get('apps') || `/dashboard/${resource}`

const componentPath = join(moduleDir, 'app', 'components', moduleId, `${pascal}.vue`)
const testPath = join(moduleDir, 'test', `${kebab}.component.test.ts`)
const generatedPath = join(moduleDir, 'server', 'chatComponents.generated.ts')

for (const path of [componentPath, testPath]) {
  if (existsSync(path)) {
    console.error(`Refusing to overwrite ${path}`)
    process.exit(1)
  }
}

mkdirSync(join(moduleDir, 'app', 'components', moduleId), { recursive: true })
mkdirSync(join(moduleDir, 'test'), { recursive: true })
mkdirSync(join(moduleDir, 'server'), { recursive: true })

const component = `<script setup lang="ts">
/**
 * Chat component \`${componentId}\` (generated by \`pnpm module:add-component\`).
 *
 * The model only supplies a query and a page size; rows come from the
 * permission-checked API. Replace the endpoint/columns below, then add the
 * detail/edit dialog through \`useChatRecord\` (or keep it read-only).
 */
const props = defineProps<{
  query?: string
  limit?: number
}>()

const rows = ref<Array<Record<string, unknown>>>([])
const loading = ref(true)
const error = ref('')

async function load(): Promise<void> {
  loading.value = true
  error.value = ''
  try {
    const response = await $fetch<{ items: Array<Record<string, unknown>> }>('/api/dashboard/data/${resource}', {
      query: {
        pageSize: Math.min(Math.max(props.limit ?? 20, 1), 100),
        ...(props.query?.trim() ? { search: props.query.trim() } : {})
      }
    })
    rows.value = Array.isArray(response.items) ? response.items : []
  } catch (value) {
    error.value = value instanceof Error ? value.message : '加载失败'
    rows.value = []
  } finally {
    loading.value = false
  }
}

onMounted(load)
watch(() => props.query, load)
</script>

<template>
  <div class="mt-2 rounded-lg border border-default">
    <p
      v-if="loading"
      class="px-2.5 py-2 text-xs text-muted"
    >
      正在加载…
    </p>
    <p
      v-else-if="error"
      class="px-2.5 py-2 text-xs text-red-600"
    >
      {{ error }}
    </p>
    <table
      v-else
      class="w-full text-left text-xs"
    >
      <thead class="bg-elevated text-toned">
        <tr>
          <th class="px-2.5 py-1.5 font-medium">
            TODO
          </th>
        </tr>
      </thead>
      <tbody>
        <tr
          v-for="(row, index) in rows"
          :key="index"
        >
          <td class="border-t border-default px-2.5 py-1.5">
            {{ row.id }}
          </td>
        </tr>
      </tbody>
    </table>
  </div>
</template>
`

const test = `import { describe, expect, it } from 'vitest'
import { isGeneratedChatTableProps } from '../server/chatComponents.generated'

describe('${componentId} props contract', () => {
  it('only accepts query/limit', () => {
    expect(isGeneratedChatTableProps({})).toBe(true)
    expect(isGeneratedChatTableProps({ query: '关键词', limit: 10 })).toBe(true)
    expect(isGeneratedChatTableProps({ query: 1 })).toBe(false)
    expect(isGeneratedChatTableProps({ limit: 0 })).toBe(false)
    expect(isGeneratedChatTableProps({ rows: [{ id: 1 }] })).toBe(false)
  })
})
`

const entry = `  {
    id: '${componentId}',
    moduleId: '${moduleId}',
    label: '${label}',
    description: '${label}（可由模型在聊天中展示）',
    propsHint: 'query?: string, limit?: number',
    version: '1.0',
    interactions: { detail: true, edit: { permission: '${componentId}.update' } },
    appsPath: '${appsPath}',
    schema: isGeneratedChatTableProps,
    render: props => ({ component: '${componentId}', props })
  },
`

const generatedTemplate = `/**
 * Chat components generated by \`pnpm module:add-component\`.
 */
import type { UiDefinition } from '../../../server/sdk'

export type GeneratedChatTableProps = { query?: string, limit?: number }

export function isGeneratedChatTableProps(value: unknown): value is GeneratedChatTableProps {
  if (typeof value !== 'object' || value === null) return false
  const record = value as Record<string, unknown>
  if ('rows' in record) return false
  if (record.query !== undefined && typeof record.query !== 'string') return false
  if (record.limit !== undefined) {
    if (typeof record.limit !== 'number' || !Number.isSafeInteger(record.limit)) return false
    if (record.limit < 1 || record.limit > 200) return false
  }
  return true
}

export const generatedChatComponents: UiDefinition<GeneratedChatTableProps, Record<string, unknown>>[] = [
  // <generated> keep this marker so the scaffold can append entries
]
`

writeFileSync(componentPath, component)
writeFileSync(testPath, test)

const generatedSource = existsSync(generatedPath) ? readFileSync(generatedPath, 'utf8') : generatedTemplate
const marker = '  // <generated> keep this marker so the scaffold can append entries'
if (!generatedSource.includes(marker)) {
  console.error(`Marker not found in ${generatedPath}; add the registration entry manually.`)
  process.exit(1)
}
const updated = generatedSource.replace(marker, `${entry}${marker}`)
writeFileSync(generatedPath, updated)

console.log(`\nCreated:\n  ${componentPath}\n  ${testPath}\n  registration → ${generatedPath}\n`)
console.log('Next steps:')
console.log(`  1. Make sure modules/${moduleId}/register.ts imports generatedChatComponents and spreads it into the UI list.`)
console.log(`  2. Replace the endpoint/columns in ${pascal}.vue and add ${resource} permissions to the module manifest.`)
console.log(`  3. Add '${componentId}' to modules/${moduleId}/module.ts components (manifest contract).`)
console.log('  4. Client rendering is automatic: the layer maps the id from the component filename.')
